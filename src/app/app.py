"""
Streamlit chat interface (DEV PROTOTYPE).

A minimal page to talk to the knowledge base: one text box, the chat history, and the sources behind each
answer. All retrieval and generation happens in src/core (rag.py); this file only displays things.
Citations are renumbered for display after an answer is complete (src/core/citations.py); the model's own text is unchanged.

Launch from the project root:  venv\\Scripts\\streamlit run src\\app\\app.py
"""

import sys
from pathlib import Path

# Make the project root importable (config/ and src/) when Streamlit runs this file directly.
PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import streamlit as st

from config import settings
from src.app import quiz_view, styles
from src.app.shared import (load_pipeline, reply_caption, show_cited_sources, show_retrieved,
                             sources_of, usage_caption)
from src.core import citations, guardrail, llm, quiz
from src.core.conversation import Conversation

st.set_page_config(page_title="Data Engineering Course Assistant", page_icon="💬")

# Bold text in the dark theme: heavier and in a light accent tint (src/app/styles.py; display only).
_css = styles.dark_bold_css(getattr(getattr(st.context, "theme", None), "type", None))
if _css:
    st.html(_css)


def show_session_counts(slot) -> None:
    """Sidebar tally of citation problems over the model answers in this chat."""
    counts = citations.session_counts([m["citations"] for m in st.session_state.messages if m.get("citations")])
    if counts["answers_checked"]:
        plural = "" if counts["answers_checked"] == 1 else "s"
        slot.caption(f"Citation check, {counts['answers_checked']} model answer{plural} in this chat: "
                     f"{counts['outside_set']} cited material not given to the model · {counts['malformed']} had a "
                     f"malformed citation · {counts['no_citation']} cited no course material")


def model_label(model: str) -> str:
    """The dropdown text for a model, with its group. st.selectbox has no option groups, so the group is a prefix."""
    group = settings.DEV_MODEL_GROUP_CLOUD if llm.is_cloud_model(model) else settings.DEV_MODEL_GROUP_LOCAL
    return f"{group} · {model}"


# ---------------------------------------------------------------- sidebar
with st.sidebar:
    st.subheader("Dev prototype")
    model_options = settings.DEV_LLM_MODEL_OPTIONS + list(settings.DEV_CLOUD_MODELS)
    # The default is the model selected in notebook 04 (settings.DEV_DEFAULT_ANSWER_MODEL), so it survives a restart.
    default_model = settings.DEV_DEFAULT_ANSWER_MODEL if settings.DEV_DEFAULT_ANSWER_MODEL in model_options else settings.DEV_LLM_MODEL
    default_index = model_options.index(default_model) if default_model in model_options else 0
    selected_model = st.selectbox("Answer model", model_options, index=default_index, format_func=model_label)
    st.session_state.answer_model = selected_model      # the Quiz and Study plan pages use the same model
    st.caption(f"New answers are generated by **{selected_model}**. Default: {settings.DEV_DEFAULT_ANSWER_MODEL}, the model "
               f"selected in notebook 04; offline model: {settings.DEV_LLM_MODEL}. Each reply shows the model that wrote it.")
    backend_ok, backend_message = llm.check_backend(selected_model)
    (st.success if backend_ok else st.error)(backend_message)
    st.caption(f"Intent classifier: {settings.DEV_LLM_MODEL} · retrieval: {settings.EMBEDDING_MODEL} · "
               f"top {settings.TOP_K} chunks · fallback below similarity {settings.SIMILARITY_THRESHOLD}")
    st.caption(settings.DEV_UI_HISTORY_CAPTION.format(n=settings.HISTORY_MAX_EXCHANGES))
    citation_counts_slot = st.empty()      # filled at the end of the page, so it includes an answer written in this run
    if st.button(settings.DEV_UI_NEW_CHAT_LABEL):     # clears the messages AND the conversation the model sees
        st.session_state.messages = []
        st.session_state.conversation = Conversation()
        st.rerun()

st.title("Data Engineering Course Assistant")
st.caption("Ask about SQL, ETL/ELT, pipelines, data cleaning, processing, quality, warehousing or big data. "
           "Answers come only from the course knowledge base and cite the chunks they use.")

if "messages" not in st.session_state:
    st.session_state.messages = []
if "conversation" not in st.session_state:     # multi-turn memory for this browser session (src/core/conversation.py)
    st.session_state.conversation = Conversation()

# ---------------------------------------------------------------- history
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        if message.get("quiz"):                       # a quiz card (feature B): rendered from its saved state
            quiz_view.render(message["quiz"], message["sources"], message["quiz_key"])
            st.caption(reply_caption(message.get("model"), False))
            if message.get("usage"):
                st.caption(usage_caption(message["usage"]))
            continue
        if message.get("failed"):
            st.error(message["content"])
        else:
            if message.get("coach_mode"):
                st.info(settings.GUARDRAIL_UI_NOTE)
            st.markdown(message["content"])
            if message.get("followup"):
                st.caption(settings.DEV_UI_FOLLOWUP_NOTE)
            if message.get("regenerated"):
                st.caption(settings.DEV_UI_REGENERATED_NOTE.format(
                    reason=settings.DEV_UI_REGENERATED_REASONS.get(message["regenerated"], message["regenerated"])))
            if message["role"] == "assistant":
                st.caption(reply_caption(message.get("model"), message.get("used_fallback", False)))
            if message.get("usage"):
                st.caption(usage_caption(message["usage"]))
            if message.get("citations"):
                show_cited_sources(message["sources"], message["citations"])
        if message.get("sources"):
            show_retrieved(message["sources"], message["used_fallback"])

# ---------------------------------------------------------------- new question
question = st.chat_input("Type your question...")
if llm.is_cloud_model(selected_model):        # privacy note under the input, in cloud mode only (author, 2026-11-28)
    st.bottom.caption(settings.DEV_CLOUD_PRIVACY_NOTE.format(host=llm.cloud_host(selected_model)))
if question:
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        if not backend_ok:
            st.error(backend_message)
        else:
            pipeline = load_pipeline()
            with st.spinner("Searching the course materials..."):
                result = pipeline.answer(question, model=selected_model, conversation=st.session_state.conversation)
            usage, failed = None, False
            answer_slot = st.empty()          # the raw answer goes here first, then the version with numbered citations
            if result.quiz_call:              # Quiz me (feature B): write and check the quiz, then show it as a card
                try:
                    if llm.is_cloud_model(result.model):
                        made = result.quiz_call(answer_slot.info)
                    else:
                        with st.spinner(settings.QUIZ_WAITING_LOCAL):
                            made = result.quiz_call()
                except (llm.CloudError, quiz.QuizError) as error:
                    st.session_state.messages.append({"role": "assistant", "content": str(error), "failed": True})
                else:
                    st.session_state.messages.append({
                        "role": "assistant", "content": f"Quiz: {made['topic']}", "quiz": made,
                        "quiz_key": f"quiz_{len(st.session_state.messages)}", "sources": sources_of(result.chunks),
                        "model": result.model, "usage": made["usage"], "used_fallback": False})
                st.rerun()                    # shown from the history, so the card keeps its state; quizzes are not in the history
            if result.cloud_call:             # a cloud answer is not streamed: show the waiting state until it is ready
                try:
                    cloud = result.cloud_call(answer_slot.info)
                except llm.CloudError as error:
                    answer, failed = str(error), True
                else:
                    answer = cloud.text
                    usage = {"input_tokens": cloud.input_tokens, "output_tokens": cloud.output_tokens,
                             "reasoning_tokens": cloud.reasoning_tokens, "cost_usd_list": cloud.cost_usd_list,
                             "latency_seconds": cloud.latency_seconds, "retries": cloud.retries,
                             "retry_wait_seconds": cloud.retry_wait_seconds}
                answer_slot.empty()
            else:
                with answer_slot.container():
                    answer = st.write_stream(result.answer_stream)
            sources = sources_of(result.chunks)
            # Coach mode (a task request): cap any long code block, whatever the model did with the instruction.
            if result.coach_mode and not failed:
                answer, _ = guardrail.cap_code_blocks(answer)
            # Only a model's answer has citations to check; fixed replies, the fallback and a failed call have none.
            check = citations.check(answer, [s["chunk_id"] for s in sources]) if result.model and not failed else None
            shown = check.text if check else answer
            if failed:
                answer_slot.error(answer)
            else:
                with answer_slot.container():
                    if result.coach_mode:
                        st.info(settings.GUARDRAIL_UI_NOTE)
                    st.markdown(shown)
                    if result.search_mode == "combined":
                        st.caption(settings.DEV_UI_FOLLOWUP_NOTE)
                    if result.regenerated:
                        st.caption(settings.DEV_UI_REGENERATED_NOTE.format(
                            reason=settings.DEV_UI_REGENERATED_REASONS.get(result.regenerated, result.regenerated)))
                st.caption(reply_caption(result.model, result.used_fallback))
            if usage:
                st.caption(usage_caption(usage))
            if check:
                show_cited_sources(sources, check.to_dict())
            if sources:                       # small talk / unclear input skips retrieval: nothing to show
                show_retrieved(sources, result.used_fallback)
            st.session_state.messages.append({"role": "assistant", "content": shown, "raw_answer": answer,
                                              "model": result.model, "sources": sources,
                                              "used_fallback": result.used_fallback, "usage": usage, "failed": failed,
                                              "citations": check.to_dict() if check else None,
                                              "coach_mode": result.coach_mode,
                                              "followup": result.search_mode == "combined",
                                              "regenerated": result.regenerated})
            # Multi-turn: remember the finished turn (the answer as shown, code already capped in coach mode).
            st.session_state.conversation.record(result, answer, failed=failed)

show_session_counts(citation_counts_slot)
